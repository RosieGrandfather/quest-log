import random
from math import sqrt
random.seed(0)

# 总体：均值 10、标准差 2（真值 mu = 10，但「研究者」并不知道）
mu, sigma, n = 10, 2, 50
half = 1.96 * sigma / sqrt(n)            # 95% 区间的「半宽」= 1.96 × 标准误

covered = 0
for i in range(1000):                    # 把整个实验重复 1000 次
    xbar = sum(random.gauss(mu, sigma) for _ in range(n)) / n   # 每次抽 50 个，取平均
