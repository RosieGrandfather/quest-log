C_MLE = code('''
# 一枚硬币抛了 10 次，7 次正面。它的「正面概率」p 是多少？
k, n = 7, 10

# 似然：如果正面概率是 p，那么「恰好出现这组结果」的概率是多少？
def likelihood(p):
    return p**k * (1 - p)**(n - k)

for p in (0.3, 0.5, 0.7, 0.9):
    print(f"p = {p}:  似然 = {likelihood(p):.5f}")

# 在 0.01 到 0.99 之间一个一个试，找似然最大的 p
best = max((i / 100 for i in range(1, 100)), key=likelihood)
print("似然最大的 p =", best, "  即 k/n =", k / n)
''')

C_LOG = code('''
from math import log

# 为什么用对数：1100 次公平硬币的一个具体结果，概率是 0.5 的 1100 次方
print("连乘：", 0.5 ** 1100)                # 比电脑能表示的最小正数还小，直接变成 0
print("取对数再连加：", round(1100 * log(0.5), 2))   # 数值稳定，而且大小顺序不变

# 二项情形：对数似然 ℓ(p) = k·ln p + (n−k)·ln(1−p)，同样在 p = k/n 处最大
k, n = 7, 10
loglik = lambda p: k * log(p) + (n - k) * log(1 - p)
best = max((i / 100 for i in range(1, 100)), key=loglik)
print("对数似然最大的 p =", best)
''')

C_NORM = code('''
import random, statistics as st
from math import log, pi

random.seed(0)
data = [random.gauss(5, 2) for _ in range(200)]     # 真实：均值 5，标准差 2

# 正态分布的最大似然估计有公式解：均值 = 样本均值，方差 = 除以 n 的方差
mu_hat = st.mean(data)
var_hat = st.pvariance(data)           # 注意：pvariance 是除以 n
print("均值的最大似然估计：", round(mu_hat, 3))
print("方差的最大似然估计：", round(var_hat, 3), "（除以 n）")
print("无偏的样本方差：    ", round(st.variance(data), 3), "（除以 n-1）")

# 验证：在 (mu_hat, var_hat) 处，对数似然确实比旁边的点大
def loglik(mu, var):
    return sum(-0.5 * log(2 * pi * var) - (x - mu) ** 2 / (2 * var) for x in data)
print("对数似然 在估计值处：", round(loglik(mu_hat, var_hat), 2))
print("对数似然 均值偏 0.3：", round(loglik(mu_hat + 0.3, var_hat), 2))
print("对数似然 方差 ×1.5： ", round(loglik(mu_hat, var_hat * 1.5), 2))
''')

